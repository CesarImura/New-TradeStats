// Booking link: editor (Join), Settings e checkout, uma fonte so. CHROME_PATH="<Chrome for Testing>" node scripts/booking-link.mjs
import { createRequire } from "node:module"
const require = createRequire("/Users/gustavorodolfo/Projetos/TradeHub/_worktrees/admin-v2/package.json")
const { chromium } = require("playwright-core")
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH })
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 } })
const p = await ctx.newPage(); const errs=[]; p.on("pageerror", e=>errs.push(e.message.slice(0,120)))
const ok = (n, v, x="") => console.log(v ? "OK  " : "FAIL", n, x)
await p.goto("http://localhost:3000/admin/kairo/design?step=join&screen=subscribe"); await p.waitForTimeout(7000)
const inp = p.getByLabel("Booking link")
ok("editor: campo Booking link visivel", await inp.isVisible().catch(()=>false))
await inp.fill("https://calendly.com/kairo-fx/intro-call"); await p.waitForTimeout(800)
ok("editor: valor salvo no store", (await p.evaluate(()=>localStorage.getItem("proto:kairo:booking"))) === JSON.stringify("https://calendly.com/kairo-fx/intro-call"))
const pg = await ctx.newPage(); await pg.goto("http://localhost:3000/site/kairo/checkout"); await pg.waitForTimeout(6000)
ok("checkout mostra Book a call com o link", (await pg.locator("a:text('Book a call')").getAttribute("href").catch(()=>null)) === "https://calendly.com/kairo-fx/intro-call")
await inp.fill("calendly.com/sem-http"); await p.waitForTimeout(600)
await pg.reload(); await pg.waitForTimeout(6000)
ok("link sem http nao aparece", (await pg.locator("a:text('Book a call')").count()) === 0)
await p.goto("http://localhost:3000/admin/kairo/settings?tab=general"); await p.waitForTimeout(5000)
ok("settings mostra o mesmo valor (uma fonte so)", (await p.getByLabel("Booking link").inputValue()) === "calendly.com/sem-http")
await p.getByLabel("Booking link").fill(""); await p.waitForTimeout(500)
await pg.reload(); await pg.waitForTimeout(6000)
ok("vazio: linha some", (await pg.locator("a:text('Book a call')").count()) === 0)
ok("sem erros", errs.length === 0, errs.join(";"))
await b.close()
